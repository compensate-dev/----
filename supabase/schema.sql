-- 一江春水 · 李煜词境 —— 后端库表结构（幂等，可重复执行）
-- 说明：本文件由 byted-supabase-cli db query -f 直接执行，非官方 migration 机制。

-- 1) 词库表：供「诗词检索 / AI 侍读」取原文与背景
create table if not exists public.poems (
  id          bigint generated always as identity primary key,
  slug        text not null unique,
  title       text not null,
  tune        text,                -- 词牌名
  year        int,                 -- 创作年份（约）
  age         int,                 -- 李煜当年岁数
  phase       text not null default 'unknown', -- early / middle / late / unknown
  content     text not null,       -- 词作正文（含标点）
  translation text,                -- 白话释义
  background  text,                -- 写作背景
  appreciation text,               -- 简评
  keywords    text[] not null default '{}',
  created_at  timestamptz not null default now()
);

comment on table public.poems is '李煜词作资料库，供站内检索与 AI 侍读引用';

-- 关键词倒排索引：检索时按关键词/意象快速命中
create index if not exists poems_keywords_idx on public.poems using gin (keywords);
-- 标题与正文模糊检索的辅助索引（中文短文本，主要靠 ILIKE）
create index if not exists poems_title_idx on public.poems (title);

-- 2) 侍读问答日志：记录用户提问与模型回答，便于回看与调优（不对外开放）
create table if not exists public.guide_logs (
  id         bigint generated always as identity primary key,
  session_id text,
  mode       text not null default 'ask',   -- ask / search / compose / interpret
  page       text,                          -- 来源页面标识（home / life / ci / listen / map / finale）
  question   text,
  answer     text,
  model      text,
  tokens     int,
  created_at timestamptz not null default now()
);

comment on table public.guide_logs is 'AI 侍读问答日志，仅服务端写入';

-- 3) 行级安全：词库只读公开；日志默认无公开策略（仅 service_role 可读写）
alter table public.poems enable row level security;
alter table public.guide_logs enable row level security;

drop policy if exists poems_public_read on public.poems;
create policy poems_public_read on public.poems
  for select to anon, authenticated
  using (true);

-- 写入权限只保留给服务端（service_role 默认绕过 RLS，这里不额外放行 anon）
revoke all on public.guide_logs from anon, authenticated;

